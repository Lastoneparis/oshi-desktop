#!/usr/bin/env python3
# __CHANNEL_WEB_2026_11_26__ desktop strings of the public channel web preview (prefix `desktop.cw.`,
# so they never collide with the iOS branch's `cw_*` keys when both trees merge), 34 languages, in
# channel_web_strings.json. 27 of the 28 values are copied verbatim from the iOS catalog
# (feat/channel-web-ios 5e3982caa, OSHI/<lang>.lproj, keys `cw_<same suffix>`); `open_browser` is
# desktop wording (a computer opens the page in its browser where a phone shows a share sheet).
# Appends one delimited block to each OSHI/<lang>.lproj/Localizable.strings (idempotent); then run
# ./gradlew i18nExtract.   Usage: channel_web_strings.py <path to OSHI/>
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, 'channel_web_strings.json'), encoding='utf-8'))
KEYS = list(S['en'].keys())
BEGIN = '/* __CHANNEL_WEB_2026_11_26__ BEGIN — generated by OSHI-Desktop/i18n-src/channel_web/channel_web_strings.py */'
END = '/* __CHANNEL_WEB_2026_11_26__ END */'
def esc(v): return v.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
if __name__ == '__main__':
    root = sys.argv[1]
    for lang, vals in S.items():
        assert list(vals.keys()) == KEYS, lang
        p = os.path.join(root, f'{lang}.lproj', 'Localizable.strings')
        s = open(p, encoding='utf-8').read()
        s = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '', s, flags=re.S).rstrip('\n') + '\n'
        lines = [BEGIN] + [f'"{k}" = "{esc(vals[k])}";' for k in KEYS] + [END]
        open(p, 'w', encoding='utf-8').write(s + '\n'.join(lines) + '\n')
    print(len(S), 'locales')
