#!/usr/bin/env python3
# __STRICT_MODE_2026_11_22__ desktop-only strings of Strict security mode (prefix `desktop.strict.`,
# so they never collide with the iOS branch's `strict_*` keys), 34 languages, in strict_strings.json.
# Appends one delimited block to each OSHI/<lang>.lproj/Localizable.strings (idempotent); then run
# ./gradlew i18nExtract.   Usage: strict_strings.py <path to OSHI/>
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, 'strict_strings.json'), encoding='utf-8'))
KEYS = list(S['en'].keys())
BEGIN = '/* __STRICT_MODE_2026_11_22__ BEGIN — generated by OSHI-Desktop/i18n-src/strict/strict_strings.py */'
END = '/* __STRICT_MODE_2026_11_22__ END */'
def esc(v): return v.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
if __name__ == '__main__':
    root = sys.argv[1]
    for lang, vals in S.items():
        assert list(vals.keys()) == KEYS, lang
        p = os.path.join(root, f'{lang}.lproj', 'Localizable.strings')
        s = open(p, encoding='utf-8').read()
        s = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '', s, flags=re.S).rstrip('\n') + '\n'
        lines = [BEGIN] + [f'"{k}" = "{esc(vals[k])}";' for k in KEYS] + [END]
        open(p, 'w', encoding='utf-8').write(s + '\n'.join(lines) + '\n')
    print(len(S), 'locales')
