#!/usr/bin/env python3
# __ADV_CHAT_PRIVACY_2026_11_26__ desktop strings of Advanced chat privacy (prefix `desktop.adv_privacy.`,
# so they never collide with the iOS branch's `adv_privacy.*` keys when both trees merge), 34 languages,
# in adv_privacy_strings.json. 20 of the 21 values are copied verbatim from the iOS catalog
# (release/ios-1.4.9, OSHI/<lang>.lproj, keys `adv_privacy.<same suffix>`); `sheet.media` is desktop
# wording ("saved or opened outside OSHI" — a computer has no Photos library to protect).
# Appends one delimited block to each OSHI/<lang>.lproj/Localizable.strings (idempotent); then run
# ./gradlew i18nExtract.   Usage: adv_privacy_strings.py <path to OSHI/>
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, 'adv_privacy_strings.json'), encoding='utf-8'))
KEYS = list(S['en'].keys())
BEGIN = '/* __ADV_CHAT_PRIVACY_2026_11_26__ BEGIN — generated by OSHI-Desktop/i18n-src/adv_privacy/adv_privacy_strings.py */'
END = '/* __ADV_CHAT_PRIVACY_2026_11_26__ END */'
def esc(v): return v.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
if __name__ == '__main__':
    root = sys.argv[1]
    for lang, vals in S.items():
        assert list(vals.keys()) == KEYS, lang
        p = os.path.join(root, f'{lang}.lproj', 'Localizable.strings')
        s = open(p, encoding='utf-8').read()
        s = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '', s, flags=re.S).rstrip('\n') + '\n'
        lines = [BEGIN] + [f'"{k}" = "{esc(vals[k])}";' for k in KEYS] + [END]
        open(p, 'w', encoding='utf-8').write(s + '\n'.join(lines) + '\n')
    print(len(S), 'locales')
